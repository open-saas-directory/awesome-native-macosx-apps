#!/usr/bin/env python3
"""Render localized READMEs from README.md and exact-source translation catalogs.

No dependencies. Missing messages fall back to English, so app submissions only
need to change README.md. --check checks generated output; --report lists gaps.
"""
import argparse
import hashlib
import html
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
LOCALES = ('ar', 'zh-CN', 'ja', 'de', 'es')
SELECTOR = '[English](README.md) · [العربية](README.ar.md) · [简体中文](README.zh-CN.md) · [日本語](README.ja.md) · [Deutsch](README.de.md) · [Español](README.es.md)'
LINK = re.compile(r'(!?)\[([^\]]*)\]\(([^\s]+?)\)')
HTML = re.compile(r'(<[^>]*>)')


def message(text, catalog, missing):
    value = text.strip()
    if not value or not any(c.isalnum() for c in value):
        return text
    if value not in catalog:
        missing.add(value)
    translated = catalog.get(value, value)
    return text[:len(text) - len(text.lstrip())] + translated + text[len(text.rstrip()):]


def inline(text, catalog, missing):
    # Only translate visible text; never alter URLs or HTML attributes.
    parts = []
    pos = 0
    for match in LINK.finditer(text):
        parts.append(message(text[pos:match.start()], catalog, missing))
        label = match[2] if match[1] else message(match[2], catalog, missing)
        parts.append(f'{match[1]}[{label}]({match[3]})')
        pos = match.end()
    parts.append(message(text[pos:], catalog, missing))
    return ''.join(parts)


def render(source, locale, catalog):
    missing = set()
    lines = []
    for line in source.splitlines():
        if line == SELECTOR or line.startswith('<!--') or not line.strip():
            lines.append(line)
            continue
        heading = re.match(r'^(#{1,6}) (.*)$', line)
        if heading:
            # Retain the English anchors used by the table of contents.
            slug = re.sub(r'[^\w\- ]', '', heading[2].lower()).replace(' ', '-')
            lines.extend((f'<a name="{slug}"></a>', ''))
            lines.append(heading[1] + ' ' + message(heading[2], catalog, missing))
        elif line.lstrip().startswith('<'):
            # App names are preserved, while descriptions and pricing are translated.
            def sub(match):
                return '<sub>' + ''.join(p if p.startswith('<') else message(p, catalog, missing)
                                         for p in HTML.split(match[1])) + '</sub>'
            line = re.sub(r'<sub>(.*?)</sub>', sub, line)
            def alt(match):
                label = match[1]
                if label.endswith(' icon'):
                    name = label[:-5]
                    label = catalog['icon'] + ' ' + name if locale in ('ar', 'es') else name + ' ' + catalog['icon']
                else:
                    label = catalog.get(label, label)
                return 'alt="' + html.escape(label, quote=True) + '"'
            line = re.sub(r'alt="([^"]*)"', alt, line)
            lines.append(line)
        else:
            if line in catalog:
                lines.append(catalog[line])
            elif line.startswith('**') and line.endswith('**'):
                lines.append('**' + message(line[2:-2], catalog, missing) + '**')
            elif line.startswith('- '):
                lines.append('- ' + inline(line[2:], catalog, missing))
            elif line.startswith('[!['):
                lines.append(line.replace('Star History Chart', catalog['Star History Chart']))
            else:
                lines.append(inline(line, catalog, missing))
    digest = hashlib.sha256(source.encode()).hexdigest()
    notice = f'<!-- Generated by scripts/sync-translations.py; edit translations/{locale}.json.\nEnglish source SHA-256: {digest}\nMissing translations fall back to English. -->\n\n'
    body = '\n'.join(lines) + '\n'
    if locale == 'ar':
        body = '<div dir="rtl" lang="ar">\n\n' + body + '\n</div>\n'
        body = body.replace('<table>', '<table dir="rtl">')
        # Isolate Latin app names from the surrounding right-to-left content.
        body = body.replace('<strong><a ', '<strong dir="ltr"><a ')
    return notice + body, missing


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated READMEs need rebuilding')
    parser.add_argument('--report', action='store_true', help='List untranslated messages')
    args = parser.parse_args()
    source = (ROOT / 'README.md').read_text()
    stale = []
    for locale in LOCALES:
        catalog = json.loads((ROOT / 'translations' / f'{locale}.json').read_text())
        output, missing = render(source, locale, catalog)
        path = ROOT / f'README.{locale}.md'
        if args.check:
            if not path.exists() or path.read_text() != output:
                stale.append(path.name)
        else:
            path.write_text(output)
        print(f'{locale}: {len(missing)} untranslated message(s)')
        if args.report:
            for text in sorted(missing):
                print(f'  {text}')
    if stale:
        parser.exit(1, 'Run python3 scripts/sync-translations.py to update: ' + ', '.join(stale) + '\n')


if __name__ == '__main__':
    main()
